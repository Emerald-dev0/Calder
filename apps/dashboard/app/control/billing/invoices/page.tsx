import Link from "next/link";
import { fmtDate, fmtInt, fmtMoney } from "@/lib/control/format";
import { requireSection } from "@/lib/control/guard";
import { paymentLedger } from "@/lib/control/queries";
import { Badge, BarList, Empty, PageHeader, Panel, Stat } from "@/control/_components/ui";

export const dynamic = "force-dynamic";

const STATUS_TONE: Record<string, "ok" | "warn" | "bad" | undefined> = {
  success: "ok",
  pending: "warn",
  failed: "bad",
};

/**
 * There is no invoice generator and no PDF store. What does exist is the
 * payment ledger: one row per checkout, written as `pending` before the
 * provider is contacted and moved to `success` only after the API verified the
 * reference server-side for the exact amount and currency. That is the auditable
 * record; the provider issues the customer-facing receipt.
 *
 * This page says so instead of showing empty "invoice" furniture.
 */
export default async function PaymentsPage() {
  await requireSection("billing");
  const ledger = await paymentLedger(100);

  return (
    <>
      <PageHeader
        eyebrow="Billing"
        title="Payments & receipts"
        subtitle="Every payment row, newest first. Provider-verified records only — no invoice documents are generated by Calder."
      />

      <div className="cp-stats">
        <Stat
          label="Verified payments"
          value={fmtInt(ledger.byStatus.find((s) => s.status === "success")?.count ?? 0)}
          hint="rows confirmed with the provider"
        />
        <Stat
          label="Pending"
          value={fmtInt(ledger.totals.pending)}
          hint="checkout started, provider has not confirmed"
        />
        <Stat label="Failed" value={fmtInt(ledger.totals.failed)} hint="never became money" />
        <Stat
          label="Refunded"
          value={fmtInt(ledger.totals.refunded)}
          hint="provider-issued refund recorded on the row"
        />
      </div>

      <div className="cp-grid cp-grid-2">
        <Panel title="Collected by currency" caption="verified payments only">
          <BarList
            items={ledger.byCurrency.map((c) => ({
              label: c.currency,
              count: c.cents,
            }))}
          />
          <p className="cp-panel-caption" style={{ marginTop: 10 }}>
            {ledger.byCurrency.length === 0
              ? "No verified payment has been recorded yet."
              : ledger.byCurrency
                  .map(
                    (c) =>
                      `${fmtMoney(c.cents, c.currency === "USD" ? "USD" : "NGN")} ${c.currency}`
                  )
                  .join(" · ")}
          </p>
        </Panel>
        <Panel title="By product" caption="what money was actually taken for">
          <BarList
            items={ledger.byKind.map((k) => ({
              label: k.kind.replace("_", " "),
              count: k.count,
            }))}
          />
          <p className="cp-panel-caption" style={{ marginTop: 10 }}>
            Counts are payment rows per product kind, including rows that never completed. Collected
            totals above count only verified payments.
          </p>
        </Panel>
      </div>

      <Panel
        title="Payments"
        caption={`latest ${Math.min(100, ledger.rows.length)} · newest first`}
        flush
      >
        {ledger.rows.length === 0 ? (
          <Empty title="No payment rows yet">
            A row is written the moment checkout starts. Nothing here is inferred from a browser
            redirect, so an empty table means no checkout has been attempted.
          </Empty>
        ) : (
          <div style={{ overflowX: "auto" }}>
            <table className="cp-table">
              <thead>
                <tr>
                  <th>Reference</th>
                  <th>Organization</th>
                  <th>Kind</th>
                  <th>Product</th>
                  <th>Status</th>
                  <th>Created</th>
                  <th>Paid</th>
                  <th className="cp-num">Amount</th>
                </tr>
              </thead>
              <tbody>
                {ledger.rows.map((r) => (
                  <tr key={r.payment.id}>
                    <td className="mono" style={{ fontSize: 12 }}>
                      {r.payment.reference}
                    </td>
                    <td>
                      <Link href={`/control/customers/organizations/${r.organization.id}`}>
                        {r.organization.name}
                      </Link>
                    </td>
                    <td>{r.payment.kind.replace("_", " ")}</td>
                    <td className="mono" style={{ fontSize: 12.5 }}>
                      {r.payment.productId}
                    </td>
                    <td>
                      <Badge tone={STATUS_TONE[r.payment.status]}>{r.payment.status}</Badge>
                    </td>
                    <td className="mono" style={{ fontSize: 12.5, color: "var(--cp-muted)" }}>
                      {fmtDate(new Date(r.payment.createdAt))}
                    </td>
                    <td className="mono" style={{ fontSize: 12.5, color: "var(--cp-muted)" }}>
                      {r.payment.paidAt ? fmtDate(new Date(r.payment.paidAt)) : "—"}
                    </td>
                    <td className="cp-num">
                      {fmtMoney(
                        r.payment.amountCents,
                        r.payment.currency === "USD" ? "USD" : "NGN"
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Panel>

      <Panel title="What is not here" caption="stated, not faked">
        <div style={{ padding: "12px 16px 16px", fontSize: 13, lineHeight: 1.7 }}>
          <ul style={{ margin: 0, paddingLeft: 18 }}>
            <li>
              <b>No invoice documents.</b> Calder does not generate PDFs or invoice numbers. The
              provider issues the customer receipt; this page is the internal record.
            </li>
            <li>
              <b>No manual charge, refund or void.</b> Money moves only through the provider, and a
              refund is recorded by the API against a verified payment — not typed here.
            </li>
            <li>
              <b>No revenue estimates.</b> A pending or abandoned row is never counted as collected.
            </li>
          </ul>
        </div>
      </Panel>
    </>
  );
}
