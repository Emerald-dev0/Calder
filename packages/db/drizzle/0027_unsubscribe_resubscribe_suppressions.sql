-- ── suppressions.organization_id derivation ─────────────────────────────────
-- organization_id is a denormalised copy of projects.organization_id. Existing
-- insert paths (SES feedback, the unsubscribe route, the dashboard action) know
-- only project_id, and those paths must keep working untouched. This trigger is
-- the single writer of the denormalised value, so the column stays correct for
-- every caller, including future ones.
CREATE OR REPLACE FUNCTION "public"."suppressions_set_organization_id"()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  SELECT p."organization_id" INTO NEW."organization_id"
  FROM "public"."projects" AS p
  WHERE p."id" = NEW."project_id";
  RETURN NEW;
END;
$$;
--> statement-breakpoint
